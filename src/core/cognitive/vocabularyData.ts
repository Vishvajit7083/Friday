export function mergeLexicons(base: LexiconEntry[], custom: LexiconEntry[]): LexiconEntry[] {
  const byPhrase = new Map<string, LexiconEntry>();
  for (const item of base) {
    byPhrase.set(item.phrase.toLowerCase(), item);
  }
  for (const item of custom) {
    byPhrase.set(item.phrase.toLowerCase(), { ...item, userAdded: item.userAdded ?? true });
  }
  return Array.from(byPhrase.values());
}
